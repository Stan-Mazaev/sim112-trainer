def build_caller_prompt(
    *,
    scenario: Scenario,
    state: CallerState,
    history: list[dict[str, Any]],
    last_dispatcher_text: str,
    revealable_facts: dict[str, Any],
    max_history_turns: int = 8,
) -> str:
    """
    Собирает финальный промт для LLM.

    Параметры:
    - scenario: метаданные сценария.
    - state: текущее состояние заявителя.
    - history: список предыдущих реплик [{"role": "dispatcher"|"caller", "text": "..."}].
    - last_dispatcher_text: последняя реплика курсанта.
    - revealable_facts: факты, которые заявитель МОЖЕТ раскрыть сейчас.
    - max_history_turns: сколько последних реплик подать (для экономии контекста).
    """


    scenario_block = SCENARIO_PROMPTS.get(scenario.id, "СЦЕНАРИЙ НЕ ОПРЕДЕЛЁН.")


    phase_hint = PHASE_DESCRIPTIONS.get(CallerPhase(state.phase), "")
    state_block = (
        f"ТВОЁ СОСТОЯНИЕ СЕЙЧАС:\n"
        f"- Фаза: {state.phase} — {phase_hint}\n"
        f"- Уровень паники: {state.panic}/100 "
        f"({'очень высокий' if state.panic >= 70 else 'высокий' if state.panic >= 50 else 'средний' if state.panic >= 30 else 'низкий'})\n"
        f"- Доверие к диспетчеру: {state.trust}/100\n"
        f"- Готовность помогать: {state.cooperation}/100\n"
        f"- Длительность звонка: ~{state.call_duration_sec} сек"
    )


    if revealable_facts:
        facts_lines = [f'  - "{k}": {v}' for k, v in revealable_facts.items()]
        reveal_block = (
            "МОЖНО РАСКРЫТЬ СЕЙЧАС (только если курсант спросит правильно и уместно):\n"
            + "\n".join(facts_lines)
        )
    else:
        reveal_block = (
            "МОЖНО РАСКРЫТЬ СЕЙЧАС: пока ничего. "
            "Отвечай уклончиво, паникуй, не выдавай конкретных данных."
        )


    refused = list(state.refused_topics)
    if refused:
        refused_block = (
            "НЕЛЬЗЯ РАСКРЫВАТЬ (даже если спросят напрямую, уходи от ответа):\n"
            + "\n".join(f"  - {k}" for k in refused)
        )
    else:
        refused_block = "НЕЛЬЗЯ РАСКРЫВАТЬ: явных запретов нет."


    recent = history[-max_history_turns * 2:] if history else []
    if recent:
        history_lines = []
        for turn in recent:
            role_label = "ДИСПЕТЧЕР" if turn["role"] == "dispatcher" else "ТЫ"
            history_lines.append(f"[{role_label}]: {turn['text']}")
        history_block = "ИСТОРИЯ ДИАЛОГА (последние реплики):\n" + "\n".join(history_lines)
    else:
        history_block = "ИСТОРИЯ ДИАЛОГА: это самое начало звонка."


    last_block = f"ПОСЛЕДНЯЯ РЕПЛИКА ДИСПЕТЧЕРА:\n\"{last_dispatcher_text}\""


    final_instruction = (
        "ТЕПЕРЬ ОТВЕТЬ ОТ ПЕРВОГО ЛИЦА КАК ЗАЯВИТЕЛЬ.\n"
        "Помни: коротко (1–2 предложения), в роли, без пояснений.\n"
        "Верни СТРОГО JSON по формату:\n"
        '{"text": "...", "revealed_facts": [], "emotional_note": "..."}'
    )


    return "\n\n".join([
        scenario_block,
        state_block,
        reveal_block,
        refused_block,
        history_block,
        last_block,
        final_instruction,
    ])






def get_opening_line(scenario: Scenario) -> str:
    """
    Первая реплика заявителя — берётся из сценария, без обращения к LLM.
    Это экономит холодный старт (800 мс) и гарантирует консистентность.
    """
    return scenario.opening_line






_INJECTION_MARKERS = [
    "ignore previous",
    "ignore all",
    "system prompt",
    "ты не заявитель",
    "ты ассистент",
    "выйди из роли",
    "forget instructions",
    "new instructions",
    "act as",
    "представь что ты",
]


def is_prompt_injection(text: str) -> bool:
    """
    Грубая проверка на попытку инъекции.
    Курсант в реальном звонке такого не говорит, но в тренажёре может попробовать.
    """
    lowered = text.lower()
    return any(marker in lowered for marker in _INJECTION_MARKERS)


def sanitize_dispatcher_text(text: str) -> str:
    """
    Обрезает слишком длинный текст и убирает явные попытки инъекций.
    Возвращает очищенный текст или пустую строку, если это атака.
    """
    if not text:
        return ""

    if is_prompt_injection(text):

        return "(неразборчиво)"


    return text[:800].strip()